"""
Run the project's SQL without installing a database server.

Loads 01_schema.sql into an in-memory DuckDB database (same SQL dialect as
PostgreSQL for everything used here), loads the raw CSVs, runs every query in
02_business_questions.sql, prints the results, and saves them to
sql/query_results.md.

Usage (from the project root):
    python sql/run_queries.py
"""
import re
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
SQL_DIR = ROOT / 'sql'
RAW = ROOT / 'data' / 'raw'

LOAD_ORDER = {  # parents before children so foreign keys are satisfied
    'customers': 'olist_customers_dataset.csv',
    'sellers': 'olist_sellers_dataset.csv',
    'category_translation': 'product_category_name_translation.csv',
    'products': 'olist_products_dataset.csv',
    'orders': 'olist_orders_dataset.csv',
    'order_items': 'olist_order_items_dataset.csv',
    'payments': 'olist_order_payments_dataset.csv',
    'reviews': 'olist_order_reviews_dataset.csv',
}


def strip_comments(sql: str) -> str:
    return '\n'.join(line.split('--')[0] for line in sql.splitlines())


def build_database() -> duckdb.DuckDBPyConnection:
    con = duckdb.connect()
    schema = (SQL_DIR / '01_schema.sql').read_text(encoding='utf-8')
    schema = '\n'.join(l for l in schema.splitlines() if not l.lstrip().startswith('\\'))  # psql-only lines
    for statement in strip_comments(schema).split(';'):
        statement = statement.strip()
        if statement and not statement.upper().startswith('DROP'):
            con.execute(statement)
    for table, file in LOAD_ORDER.items():
        con.execute(f"COPY {table} FROM '{(RAW / file).as_posix()}' (FORMAT csv, HEADER true)")
        print(f"Loaded {table:<22} {con.execute(f'SELECT COUNT(*) FROM {table}').fetchone()[0]:>9,} rows")
    return con


def parse_queries():
    text = (SQL_DIR / '02_business_questions.sql').read_text(encoding='utf-8')
    blocks = re.split(r'^(?=-- Q\d+\.)', text, flags=re.M)[1:]
    for block in blocks:
        title = block.splitlines()[0].lstrip('- ').strip()
        sql = strip_comments(block).strip().rstrip(';')
        yield title, sql


def main():
    con = build_database()
    report = ['# SQL query results', '',
              'Generated by `python sql/run_queries.py` from the raw Olist data.', '']
    for title, sql in parse_queries():
        df = con.execute(sql).df()
        print(f'\n{title}\n{df.to_string(index=False)}')
        report += [f'## {title}', '', '```sql', sql, '```', '', df.to_markdown(index=False), '']
    (SQL_DIR / 'query_results.md').write_text('\n'.join(report), encoding='utf-8')
    print(f"\nSaved results to {SQL_DIR / 'query_results.md'}")


if __name__ == '__main__':
    main()
